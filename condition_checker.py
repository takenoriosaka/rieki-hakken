"""
商品状態チェッカー

仕入れ候補のタイトルから状態を判定し、
メルカリ販売推定価格への補正係数を返す。

メルカリ中央値の基準状態 = 「良品・AB品相当（目立った傷なし）」= 1.00x

補正係数の考え方:
  - 新品は中古より大幅に高く売れる（+30%程度）
  - 美品・極美品はやや高く売れる（+5〜15%）
  - 傷・汚れありは安く売らないと売れない（-20〜60%）
  - 状態記載なし = 不明 → 保守的に-10%
"""

from dataclasses import dataclass

@dataclass
class ConditionResult:
    label: str    # 表示用ラベル（例: "美品", "傷あり"）
    factor: float # 価格補正係数（中央値に掛ける）
    rank: int     # 並び替え用ランク（高いほど良い状態）


# 状態判定テーブル（優先度順 = リストの上から評価）
_CONDITION_TABLE: list[tuple[list[str], ConditionResult]] = [
    # ── 新品・未使用 ──
    (
        ["新品未使用", "新品・未使用", "未使用品", "デッドストック"],
        ConditionResult("新品・未使用", 1.30, 10),
    ),
    # ── 未使用に近い / 極美品 ──
    # ("新品" は "新品同様" の部分文字列、"未使用" は "未使用に近い"/"ほぼ未使用" の
    #  部分文字列なので、下の「新品・未使用」汎用エントリより先に判定する必要がある
    (
        ["未使用に近い", "ほぼ未使用", "ほぼ新品", "新品同様", "極美品", "超美品", "SA品", "Sランク"],
        ConditionResult("未使用に近い", 1.15, 8),
    ),
    (
        ["新品", "未使用", "タグ付き", "タグ有り", "未着用", "未開封"],
        ConditionResult("新品・未使用", 1.30, 10),
    ),
    # ── 美品 ──
    (
        ["美品", "Aランク", "A品", "ほぼ美品", "ほぼA品"],
        ConditionResult("美品", 1.05, 7),
    ),
    # ── 良品 / AB品（基準） ──
    (
        ["良品", "AB品", "ABランク", "AB品相当", "目立った傷や汚れなし", "目立つ傷なし",
         "目立った傷なし", "状態良好", "綺麗"],
        ConditionResult("良品", 1.00, 6),
    ),
    # ── B品 / 使用感あり ──
    (
        ["B品", "Bランク", "使用感あり", "使用感有り", "使用感少々",
         "経年", "ヴィンテージ感", "アンティーク感"],
        ConditionResult("使用感あり", 0.80, 4),
    ),
    # ── やや傷・汚れ ──
    (
        ["やや傷", "やや汚れ", "小傷", "薄い傷", "若干の傷", "若干傷",
         "C品", "Cランク", "BC品", "BCランク"],
        ConditionResult("やや傷・汚れ", 0.70, 3),
    ),
    # ── 傷・汚れあり ──
    (
        ["傷あり", "傷有り", "汚れあり", "汚れ有り", "傷・汚れあり", "傷汚れあり",
         "傷や汚れ", "使用感多"],
        ConditionResult("傷・汚れあり", 0.60, 2),
    ),
    # ── 難あり / ジャンク ──
    (
        ["難あり", "難有り", "訳あり", "ジャンク", "D品", "Dランク",
         "要修理", "修理必要", "破損", "汚損", "傷多数", "大きな傷"],
        ConditionResult("難あり", 0.40, 1),
    ),
]

# 状態記載なしのデフォルト（保守的に-10%）
_DEFAULT = ConditionResult("状態不明", 0.90, 5)


def check(title: str) -> ConditionResult:
    """
    商品タイトルから状態を判定して補正係数を返す。
    複数ワードが一致した場合は最初にマッチしたもの（優先度高）を採用。
    """
    for keywords, result in _CONDITION_TABLE:
        if any(kw in title for kw in keywords):
            return result
    return _DEFAULT


# ──────────────────────────────────────────────────────────────────────────────
# 写真からの状態判定（photo_reader）とタイトルの状態の組み合わせ
# ──────────────────────────────────────────────────────────────────────────────

# 写真から判定した状態のランク（photo_reader が Claude に5段階で答えさせる）→ 補正係数。
# 写真の AI 判定は出品者の自己申告より厳しめ（袖口のテカり・糸くず程度でも「やや傷あり」と答える）で、
# メルカリ売却済みの中央値（基準 1.00）にもその程度の使用感の中古品が多く含まれるため、
# タイトル判定の表より一段ゆるい係数にする（2026-11 の実スキャンで、やや傷あり=0.70 だと
# 中古の案件の約6割が利益不足で外れた）。
#   目立った傷なし 1.00 / やや傷あり 0.85 / 傷あり 0.70（タイトルの「やや傷」相当）/ 状態悪い 0.45
# 「新品同様」は写真だけでは未使用かどうか分からないため、写真だけでは 1.00 より上げない。
# タイトルに「新品」「未使用に近い」等とあり写真も「新品同様」なら、タイトルの係数のまま（下の combine 参照）
PHOTO_RANKS: dict[str, tuple[float, int]] = {
    "新品同様":       (1.00, 8),
    "目立った傷なし": (1.00, 6),
    "やや傷あり":     (0.85, 4),
    "傷あり":         (0.70, 3),
    "状態悪い":       (0.45, 1),
}
PHOTO_RANK_ORDER = list(PHOTO_RANKS)
_DEFAULT_PHOTO_CLEAN = 1.00   # 写真で傷・汚れが見つからなかったランク（新品同様・目立った傷なし）の係数


def combine(text: ConditionResult, photo: dict | None) -> ConditionResult:
    """タイトルの状態（text）と写真の状態（photo = photo_reader の判定結果）を保守的に組み合わせる。
    ・写真の判定が無い → タイトルのまま
    ・タイトルに状態の記載あり → 悪いほう（係数が小さいほう）。写真で傷・汚れが見つからなければタイトルのまま
    ・タイトルが状態不明（0.90） → 写真で傷・汚れが見つかればその係数。見つからなければ写真の判定を使うが、
      確信度が「低」のときは状態不明の 0.90 より上げない
    ラベルは写真の判定を使ったとき「（写真）」を付ける"""
    rank = (photo or {}).get("rank")
    if rank not in PHOTO_RANKS:
        return text
    factor, order = PHOTO_RANKS[rank]
    label = f"{rank}（写真）"
    if text is not _DEFAULT:
        # 写真で傷・汚れが見つからなかった（新品同様・目立った傷なし）ときはタイトルの状態のまま
        # （タグ付き新品の写真は「目立った傷なし」と答えることが多く、下げる理由にならない）
        if factor >= _DEFAULT_PHOTO_CLEAN or factor >= text.factor:
            return text
        return ConditionResult(label, factor, order)
    if (photo or {}).get("confidence") == "低" and factor > _DEFAULT.factor:
        return ConditionResult(f"{rank}（写真・確信度低）", _DEFAULT.factor, _DEFAULT.rank)
    return ConditionResult(label, factor, order)


def is_unknown(result: ConditionResult) -> bool:
    """タイトルから状態が分からなかったか"""
    return result is _DEFAULT
